export default async function handler(req, res) {
  if (req.method !== "POST") {
    return res.status(405).json({ error: "Method not allowed. Use POST." });
  }

  const {
    recipientEmail,
    month = "August 2026",
    currency = "BDT",
    spentFormatted = "৳0.00",
    budgetFormatted = "৳0.00",
    budgetUsed = 0,
    remainingFormatted = "৳0.00",
    incomeFormatted = "৳0.00",
    savedFormatted = "৳0.00",
    categories = [],
    displayName = "User"
  } = req.body || {};

  if (!recipientEmail || typeof recipientEmail !== "string" || !recipientEmail.includes("@")) {
    return res.status(400).json({ error: "A valid recipient email address is required." });
  }

  const emailSubject = `📊 Money Copilot Report - ${month}`;

  const categoryRows = (categories || []).slice(0, 6).map((cat) => `
    <tr>
      <td style="padding: 10px 14px; border-bottom: 1px solid #edf2f7; color: #1a202c; font-weight: 600;">${cat.name}</td>
      <td style="padding: 10px 14px; border-bottom: 1px solid #edf2f7; color: #4a5568; text-align: right;">${cat.amountFormatted || cat.amount}</td>
    </tr>
  `).join("");

  const emailHtml = `
    <!DOCTYPE html>
    <html>
    <head>
      <meta charset="utf-8">
      <meta name="viewport" content="width=device-width, initial-scale=1.0">
      <title>${emailSubject}</title>
    </head>
    <body style="margin: 0; padding: 0; background-color: #f4f7fb; font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, Helvetica, Arial, sans-serif; color: #2d3748;">
      <table width="100%" cellpadding="0" cellspacing="0" style="background-color: #f4f7fb; padding: 30px 15px;">
        <tr>
          <td align="center">
            <table width="100%" cellpadding="0" cellspacing="0" style="max-width: 600px; background-color: #ffffff; border-radius: 16px; overflow: hidden; box-shadow: 0 10px 30px rgba(0,0,0,0.08); border: 1px solid #e2e8f0;">
              
              <!-- Header -->
              <tr>
                <td style="background: linear-gradient(135deg, #1e3c72 0%, #2a5298 100%); padding: 32px 28px; text-align: center; color: #ffffff;">
                  <img src="https://expense-chat-ai-sandy.vercel.app/assets/logo/logo-mark.svg" width="48" height="48" alt="Money Copilot" style="margin-bottom: 12px; vertical-align: middle;">
                  <h1 style="margin: 0; font-size: 24px; font-weight: 700; letter-spacing: -0.5px;">Money Copilot</h1>
                  <p style="margin: 6px 0 0; font-size: 14px; opacity: 0.9;">Monthly Financial Report • ${month}</p>
                </td>
              </tr>

              <!-- Main Content -->
              <tr>
                <td style="padding: 32px 28px;">
                  <p style="margin-top: 0; font-size: 16px; line-height: 1.5; color: #4a5568;">Hi <strong>${displayName}</strong>,</p>
                  <p style="font-size: 15px; line-height: 1.5; color: #4a5568;">Here is your private monthly financial summary generated by <strong>Money Copilot AI</strong>.</p>
                  
                  <!-- Stat Cards Grid -->
                  <table width="100%" cellpadding="0" cellspacing="0" style="margin: 24px 0;">
                    <tr>
                      <td width="48%" style="padding: 16px; background-color: #f8fafc; border: 1px solid #e2e8f0; border-radius: 12px;">
                        <span style="font-size: 12px; color: #718096; text-transform: uppercase; font-weight: 600; letter-spacing: 0.5px; display: block; margin-bottom: 4px;">Total Spent</span>
                        <strong style="font-size: 20px; color: #e53e3e;">${spentFormatted}</strong>
                      </td>
                      <td width="4%"></td>
                      <td width="48%" style="padding: 16px; background-color: #f8fafc; border: 1px solid #e2e8f0; border-radius: 12px;">
                        <span style="font-size: 12px; color: #718096; text-transform: uppercase; font-weight: 600; letter-spacing: 0.5px; display: block; margin-bottom: 4px;">Budget Limit</span>
                        <strong style="font-size: 20px; color: #2b6cb0;">${budgetFormatted}</strong>
                      </td>
                    </tr>
                    <tr><td height="12"></td></tr>
                    <tr>
                      <td width="48%" style="padding: 16px; background-color: #f8fafc; border: 1px solid #e2e8f0; border-radius: 12px;">
                        <span style="font-size: 12px; color: #718096; text-transform: uppercase; font-weight: 600; letter-spacing: 0.5px; display: block; margin-bottom: 4px;">Remaining Funds</span>
                        <strong style="font-size: 20px; color: #38a169;">${remainingFormatted}</strong>
                      </td>
                      <td width="4%"></td>
                      <td width="48%" style="padding: 16px; background-color: #f8fafc; border: 1px solid #e2e8f0; border-radius: 12px;">
                        <span style="font-size: 12px; color: #718096; text-transform: uppercase; font-weight: 600; letter-spacing: 0.5px; display: block; margin-bottom: 4px;">Budget Used</span>
                        <strong style="font-size: 20px; color: #d69e2e;">${budgetUsed}%</strong>
                      </td>
                    </tr>
                  </table>

                  ${categoryRows ? `
                  <h3 style="font-size: 16px; color: #2d3748; margin-top: 28px; margin-bottom: 12px; font-weight: 700;">Top Spending Categories</h3>
                  <table width="100%" cellpadding="0" cellspacing="0" style="border-collapse: collapse; background-color: #ffffff; border: 1px solid #e2e8f0; border-radius: 10px; overflow: hidden;">
                    <thead>
                      <tr style="background-color: #edf2f7; text-align: left;">
                        <th style="padding: 10px 14px; font-size: 12px; color: #4a5568; text-transform: uppercase;">Category</th>
                        <th style="padding: 10px 14px; font-size: 12px; color: #4a5568; text-transform: uppercase; text-align: right;">Amount</th>
                      </tr>
                    </thead>
                    <tbody>
                      ${categoryRows}
                    </tbody>
                  </table>
                  ` : ''}

                  <!-- CTA Button -->
                  <div style="margin-top: 32px; text-align: center;">
                    <a href="https://expense-chat-ai-sandy.vercel.app/dashboard" style="display: inline-block; padding: 14px 28px; background-color: #2563eb; color: #ffffff; text-decoration: none; font-weight: 600; font-size: 15px; border-radius: 10px; box-shadow: 0 4px 14px rgba(37, 99, 235, 0.35);">Open Money Copilot Dashboard</a>
                  </div>
                </td>
              </tr>

              <!-- Footer -->
              <tr>
                <td style="padding: 24px 28px; background-color: #f8fafc; border-top: 1px solid #e2e8f0; text-align: center; font-size: 12px; color: #a0aec0; line-height: 1.5;">
                  <p style="margin: 0;">🔒 <strong>Private & Secure</strong> — Sent from your Money Copilot workspace.</p>
                  <p style="margin: 6px 0 0;">© 2026 Money Copilot AI. All rights reserved.</p>
                </td>
              </tr>
            </table>
          </td>
        </tr>
      </table>
    </body>
    </html>
  `;

  const resendApiKey = process.env.RESEND_API_KEY;
  if (resendApiKey) {
    try {
      const response = await fetch("https://api.resend.com/emails", {
        method: "POST",
        headers: {
          "Authorization": `Bearer ${resendApiKey}`,
          "Content-Type": "application/json"
        },
        body: JSON.stringify({
          from: process.env.EMAIL_FROM || "Money Copilot <onboarding@resend.dev>",
          to: [recipientEmail],
          subject: emailSubject,
          html: emailHtml
        })
      });

      if (!response.ok) {
        const errorData = await response.json();
        console.error("Resend API error:", errorData);
        return res.status(500).json({ error: errorData.message || "Failed to send email via Resend." });
      }

      const data = await response.json();
      return res.status(200).json({ success: true, message: `Report sent successfully to ${recipientEmail}`, id: data.id });
    } catch (err) {
      console.error("Email send exception:", err);
      return res.status(500).json({ error: "Failed to dispatch email report." });
    }
  }

  console.log(`[Money Copilot Email Dispatcher] Report queued for ${recipientEmail}:`, {
    month,
    spentFormatted,
    budgetFormatted,
    budgetUsed
  });

  return res.status(200).json({
    success: true,
    simulated: true,
    message: `Report for ${month} sent successfully to ${recipientEmail}.`
  });
}
